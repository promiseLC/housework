"""Generate Pydantic v2 schema classes from the approved 0.1.2 contract."""
from pathlib import Path
import yaml
root = Path(__file__).resolve().parents[2]
spec = yaml.safe_load((root / "docs/backend/openapi.yaml").read_text())
schemas = spec["components"]["schemas"]
lines = ["# Generated by scripts/generate_schemas.py; review the source contract before regenerating.", "from datetime import datetime, timezone", "from typing import Literal", "from uuid import UUID", "from pydantic import BaseModel, Field, field_validator", "", "class ContractModel(BaseModel):", "    @field_validator('*', mode='after')", "    @classmethod", "    def utc_datetimes(cls, value):", "        return value.replace(tzinfo=timezone.utc) if isinstance(value, datetime) and value.tzinfo is None else value", "    @field_validator('username', mode='before', check_fields=False)", "    @classmethod", "    def trim_username(cls, value):", "        return value.strip() if isinstance(value, str) else value", ""]
done = set()
def merged(s):
    result = dict(s)
    if "allOf" in s:
        result = {"properties": {}, "required": []}
        for part in s["allOf"]:
            sub = merged(schemas[part["$ref"].split("/")[-1]]) if "$ref" in part else merged(part)
            result["properties"].update(sub.get("properties", {}))
            result["required"].extend(sub.get("required", []))
        result["nullable"] = s.get("nullable", False)
    return result

def typ(s):
    if "$ref" in s:
        n=s["$ref"].split("/")[-1]; emit(n); return n
    if "allOf" in s and len(s["allOf"]) == 1:
        return typ(s["allOf"][0])
    if "enum" in s: return "Literal[" + ", ".join(repr(x) for x in s["enum"]) + "]"
    if s.get("type") == "object" and "properties" in s:
        n="ErrorDetail"
        if n not in schemas: schemas[n]=s
        emit(n)
        return n
    t=s.get("type", "object")
    if t == "string": return {"uuid": "UUID", "date-time": "datetime"}.get(s.get("format"), "str")
    if t == "array": return "list[" + typ(s["items"]) + "]"
    return {"integer": "int", "boolean": "bool", "number": "float", "object": "dict"}[t]

def emit(name):
    if name in done: return
    s=schemas[name]
    if s.get("type") == "string":
        value=typ(s); lines.append(name + " = " + value); lines.append(""); done.add(name); return
    s=merged(s); fields=[]
    for key, value in s.get("properties", {}).items():
        t=typ(value)
        optional=key not in s.get("required", [])
        if value.get("nullable"): t += " | None"
        args=[]
        for source,target in [("minLength","min_length"),("maxLength","max_length"),("minItems","min_length"),("maximum","le"),("minimum","ge"),("pattern","pattern")]:
            if source in value: args.append(target + "=" + repr(value[source]))
        if value.get("type") == "integer": args.append("strict=True")
        default="None" if optional else "..."
        fields.append("    " + key + ": " + t + " = Field(" + ", ".join([default]+args) + ")")
    lines.extend(["class " + name + "(ContractModel):"] + (fields or ["    pass"]) + [""])
    done.add(name)
for name in list(schemas): emit(name)
(root / "backend/app/schemas.py").write_text("\n".join(lines) + "\n")
